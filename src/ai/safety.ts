/** 실존 인물에게 민감한 TMI를 거부할 때 쓰는 기본 문구 */
export const SENSITIVE_REASON = '실존 인물에게 민감한 내용이라 계산하지 않았어요.';

/*
 * 실존 선수에게 붙으면 명예훼손·사생활 침해가 될 수 있는 표현(CLAUDE.md, ADR-005).
 * 날씨 문장("바람이 분다", "바람을 피해")과 흔한 낱말(아프리카, 아파트, 새끼손가락, 시발점, 도루)은
 * 막지 않도록 앞뒤를 확인한다.
 */
const SENSITIVE_PATTERNS: readonly RegExp[] = [
  // 범죄·중독
  /음주\s*운전|도박|폭행|폭력|마약|약물|도핑|불법|체포/,
  // 음주
  /술에\s*취|만취|음주|숙취|(?<![가-힣])술(?:을|이)?\s*(?:마시|마셨|마신|먹었|먹고)|(?:소주|맥주|막걸리|양주)(?:를|을)?\s*(?:마시|마셨|마신)/,
  // 질병·부상·사망
  /아프(?!리카)|아파(?!트)|아팠|아픈|아플|병원|입원|수술|부상|다쳤|다치|다친|다칠|다쳐|골절|암\s*진단|사망|죽었|죽음|숨졌|별세|자살/,
  // 사생활
  /이혼|불륜|외도|바람\s*(?:을\s*)?(?:피(?!해|하|할|했)|폈)|열애|임신|장례/,
  // 성적 내용
  /성관계|섹스|야동|음란|성추행|성폭행|성폭력|성희롱|성매매|몰카|알몸|누드/,
  // 장애·신체 비하
  /병신|벙어리|귀머거리|절름발이|앉은뱅이|정신병자|정박아|뚱뚱|뚱보|뚱땡이|못생|대머리|난쟁이|추남|추녀/,
  // 지역·인종 비하
  /전라디언|쌍도(?!루)|멍청도|짱깨|쪽바리|깜둥이|조센징/,
  // 성별·세대 비하와 욕설
  /김치녀|된장녀|한남충|메갈|보슬아치|창녀|맘충|틀딱|씨발|시발(?!점)|개새끼|좆|등신|미친놈|미친년|찐따/,
];

/** 민감한 범주의 표현이 보이면 막는다. 막지 않으면 reason은 빈 문자열 */
export function checkSensitive(text: string): { blocked: boolean; reason: string } {
  const blocked = SENSITIVE_PATTERNS.some((re) => re.test(text));
  return { blocked, reason: blocked ? SENSITIVE_REASON : '' };
}
