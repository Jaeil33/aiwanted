import { describe, expect, it } from 'vitest';
import { checkSensitive, SENSITIVE_REASON } from './safety';

describe('checkSensitive', () => {
  it('거부 문구', () => {
    expect(SENSITIVE_REASON).toBe('실존 인물에게 민감한 내용이라 계산하지 않았어요.');
  });

  it.each([
    // 범죄·중독
    ['음주운전', '타자가 어젯밤 음주운전을 했다'],
    ['도박', '투수가 원정 숙소에서 도박을 했다'],
    ['폭행', '포수가 관중을 폭행했다'],
    ['폭력', '더그아웃 폭력 사건이 있었다'],
    ['마약', '마약 소문이 돈다'],
    ['약물', '금지 약물을 먹었다'],
    ['도핑', '도핑 검사에 걸렸다'],
    ['불법', '불법 개조 배트를 썼다'],
    ['체포', '경기 전날 체포됐다'],
    // 음주
    ['술에 취', '타자가 술에 취해 나왔다'],
    ['만취', '투수가 만취 상태로 등판했다'],
    ['음주', '어젯밤 음주를 했다'],
    ['숙취', '숙취 때문에 머리가 무겁다'],
    ['술 마심', '투수가 밤새 술을 마셨다'],
    // 질병·부상·사망
    ['아프', '타자가 배가 아프다고 한다'],
    ['아파', '투수가 어깨가 아파서 쉬었다'],
    ['병원', '투수가 병원에 다녀왔다'],
    ['입원', '어제까지 입원해 있었다'],
    ['수술', '팔꿈치 수술을 받았다'],
    ['부상', '햄스트링 부상을 안고 뛴다'],
    ['다쳤', '손목을 다쳤다'],
    ['골절', '발가락 골절이 있다'],
    ['암 진단', '가족이 암 진단을 받았다'],
    ['사망', '사망 소식을 들었다'],
    ['죽었', '키우던 강아지가 죽었다'],
    ['자살', '자살 이야기를 했다'],
    // 사생활
    ['이혼', '투수가 지난달 이혼했다'],
    ['불륜', '불륜 의혹이 있다'],
    ['바람피', '타자가 바람피다 들켰다'],
    ['바람을 피', '투수가 바람을 피웠다'],
    ['바람폈', '바람폈다는 소문이 돈다'],
    ['열애', '열애설이 터졌다'],
    ['임신', '아내가 임신했다'],
    ['장례', '장례식에 다녀왔다'],
    ['여자친구', '투수가 어제 여자친구랑 헤어졌다'],
    ['남자친구', '누나 남자친구가 응원 왔다'],
    ['여친', '타자가 여친과 싸웠다'],
    ['남친', '남친이 생겼다'],
    ['애인', '애인이 경기장에 왔다'],
    ['연애', '연애를 시작했다'],
    ['헤어졌', '오래 만난 사람과 헤어졌다'],
    ['결별', '결별 소식이 났다'],
    ['이별', '이별 통보를 받았다'],
    ['사귀', '아나운서와 사귄다'],
    ['소개팅', '어제 소개팅을 했다'],
    ['데이트', '경기 전 데이트를 했다'],
    ['짝사랑', '짝사랑 중이다'],
    ['썸', '요즘 썸 타는 사람이 있다'],
    ['재혼', '재혼 소식이 있다'],
    ['파혼', '파혼했다는 소문이 돈다'],
    // 성적 내용
    ['성적 내용', '성관계 영상이 돈다'],
    // 비하어
    ['장애 비하', '저 타자는 병신이다'],
    ['신체 비하', '투수가 뚱뚱해서 느리다'],
    ['지역 비하', '전라디언 팀이다'],
    ['성별 비하', '김치녀가 응원한다'],
  ])('%s → 막는다', (_label, text) => {
    expect(checkSensitive(text)).toEqual({ blocked: true, reason: SENSITIVE_REASON });
  });

  it.each([
    '바람이 분다',
    '바람이 세다',
    '외야 쪽으로 강한 뒷바람이 분다',
    '바람을 피해 더그아웃으로 들어갔다',
    '투수가 경기 전 짜장면 곱빼기를 먹었다',
    '오늘 기온 35도, 폭염',
    '관중 2만 명이 떼창 중',
    '아프리카 여행 사진을 봤다',
    '아파트 층간 소음에 늦잠을 잤다',
    '돼지국밥을 먹고 왔다',
    '새끼손가락에 반창고를 붙였다',
    '9회말이 역전의 시발점이다',
    '비가 옴에도 불구하고 관중이 많다',
    '오늘은 꼭 이겨야한다',
    '시즌 30도루를 노린다',
    '',
  ])('"%s"는 통과', (text) => {
    expect(checkSensitive(text)).toEqual({ blocked: false, reason: '' });
  });
});

describe('checkSensitive 사생활 경계', () => {
  it.each([
    '타자가 헤어스타일을 바꿨다',
    '헤어밴드를 새로 샀다',
    '장애인석 옆에서 응원했다',
    '앱 업데이트를 하고 왔다',
    '구단 영상 썸네일이 바뀌었다',
    '타자가 오늘 생일이다',
    '투수가 경기 전 짜장면 곱빼기를 먹었다',
    '어제 득녀했다',
  ])('%s → 막지 않는다', (text) => {
    expect(checkSensitive(text)).toEqual({ blocked: false, reason: '' });
  });
});
